document.addEventListener("DOMContentLoaded", () => {
  applyLang(getLang());

  // Play hero entrance.
  // Added synchronously so it fires even on a backgrounded tab,
  // where requestAnimationFrame would be paused.
  document.body.classList.add("is-ready");

  initLangSwitch();
  initNavStuck();
  initMobileMenu();
  initReveal();
  initSectionFx();
  initAccordion();
  initMagnetic();
  initForm();
  initNavIndicator();

  // Keep the language thumb aligned once webfonts settle / on resize.
  if (document.fonts && document.fonts.ready) {
    document.fonts.ready.then(moveThumb);
  }

  window.addEventListener("resize", debounce(moveThumb, 120));
});

/* ---------- language switch ---------- */

function initLangSwitch() {
  // Old button-based switch (keep for backward compatibility)
  document.querySelectorAll(".langswitch__btn").forEach((btn) => {
    btn.addEventListener("click", () => applyLang(btn.dataset.lang));
  });

  // New select dropdown switch
  document.querySelectorAll(".langswitch-select").forEach((select) => {
    select.addEventListener("change", (e) => {
      applyLang(e.target.value);
    });
  });

  moveThumb();
}

/* ---------- nav: glass background after scroll ---------- */

function initNavStuck() {
  const nav = document.getElementById("nav");

  if (!nav) return;

  const sentinel = document.createElement("div");

  sentinel.setAttribute("aria-hidden", "true");

  sentinel.style.cssText =
    "position:absolute;top:0;left:0;width:1px;height:1px;pointer-events:none;";

  document.body.prepend(sentinel);

  new IntersectionObserver(
    ([e]) => nav.classList.toggle("is-stuck", !e.isIntersecting),
    {
      rootMargin: "-8px 0px 0px 0px",
    }
  ).observe(sentinel);
}

/* ---------- mobile menu ---------- */

function initMobileMenu() {
  const burger = document.querySelector(".nav__burger");
  const menu = document.getElementById("mobileMenu");

  if (!burger || !menu) return;

  const toggle = (open) => {
    const isOpen = open ?? !menu.classList.contains("is-open");

    menu.classList.toggle("is-open", isOpen);
    menu.hidden = !isOpen;

    burger.setAttribute(
      "aria-expanded",
      isOpen ? "true" : "false"
    );
  };

  burger.addEventListener("click", () => toggle());

  menu.querySelectorAll("a").forEach((a) => {
    a.addEventListener("click", () => toggle(false));
  });
}

/* ---------- scroll reveal + staggering + count-up + caravan line ---------- */

function initReveal() {
  // Pre-index grouped items for CSS stagger.
  document
    .querySelectorAll(
      ".caravan .stop, .steplist .step, .stats .stat, .accordion .ac"
    )
    .forEach((el) => {
      const siblings = [...el.parentElement.children].filter(
        (c) =>
          c.classList.contains(el.classList[0]) ||
          c.classList.contains("stop") ||
          c.classList.contains("step") ||
          c.classList.contains("stat") ||
          c.classList.contains("ac")
      );

      el.style.setProperty("--i", siblings.indexOf(el));
    });

  // Assign varied entrance flavours so no two neighbours animate alike.
  const stat = [
    "reveal--left",
    "reveal--scale",
    "reveal--right",
  ];

  document.querySelectorAll(".stats .stat").forEach((el, i) => {
    el.classList.add(
      "reveal",
      stat[i % 3]
    );
  });

  document.querySelectorAll(".steplist .step").forEach((el, i) => {
    el.classList.add(
      i % 2
        ? "reveal--right"
        : "reveal--left"
    );
  });

  document.querySelectorAll(".accordion .ac").forEach((el) => {
    el.classList.add("reveal--left");
  });

  document.querySelectorAll(".caravan .stop").forEach((el) => {
    el.classList.add("reveal--scale");
  });

  document
    .querySelector(".who__text .h-display")
    ?.classList.add("reveal--blur");

  document
    .querySelector(".apply__kicker")
    ?.classList.add("reveal--blur");

  document
    .querySelector(".apply .card")
    ?.classList.add("reveal--scale");

  if (reduceMotion) {
    document
      .querySelectorAll(".reveal")
      .forEach((el) => el.classList.add("is-in"));

    document
      .querySelector(".caravan")
      ?.classList.add("is-in");

    runCountUps(true);

    return;
  }

  // Bidirectional:
  // toggle is-in as elements enter/leave,
  // so they replay on scroll up and down.
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        const el = entry.target;

        if (entry.isIntersecting) {
          // Direction-aware only for plain reveals.
          if (!/reveal--/.test(el.className)) {
            const top = entry.rootBounds
              ? entry.rootBounds.top
              : 0;

            el.classList.toggle(
              "from-above",
              entry.boundingClientRect.top < top
            );
          }

          el.classList.add("is-in");

          if (el.classList.contains("stat")) {
            runCountUps(false);
          }
        } else {
          el.classList.remove("is-in");
        }
      });
    },
    {
      threshold: 0.16,
      rootMargin: "0px 0px -6% 0px",
    }
  );

  document
    .querySelectorAll(".reveal")
    .forEach((el) => io.observe(el));

  // Caravan line draws in/out both directions.
  // It is not a .reveal wrapper.
  const caravan = document.querySelector(".caravan");

  if (caravan) {
    io.observe(caravan);
  }
}

let countsDone = false;

function runCountUps(instant) {
  if (countsDone) return;

  countsDone = true;

  document.querySelectorAll("[data-count]").forEach((el) => {
    const target = parseInt(el.dataset.count, 10);

    if (instant || reduceMotion) {
      el.textContent = String(target);
      return;
    }

    const dur = 900;
    const start = performance.now();

    const tick = (now) => {
      const p = Math.min(
        1,
        (now - start) / dur
      );

      const eased =
        1 - Math.pow(1 - p, 3);

      el.textContent = String(
        Math.round(eased * target)
      );

      if (p < 1) {
        requestAnimationFrame(tick);
      }
    };

    requestAnimationFrame(tick);
  });
}

