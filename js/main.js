/* ---------- nav: glass background after scroll ---------- */
function initNavStuck() {
  const nav = document.getElementById("nav");
  const sentinel = document.createElement("div");
  sentinel.setAttribute("aria-hidden", "true");
  sentinel.style.cssText = "position:absolute;top:0;left:0;width:1px;height:1px;pointer-events:none;";
  document.body.prepend(sentinel);
  new IntersectionObserver(
    ([e]) => nav.classList.toggle("is-stuck", !e.isIntersecting),
    { rootMargin: "-8px 0px 0px 0px" }
  ).observe(sentinel);
}

/* ---------- mobile menu ---------- */
function initMobileMenu() {
  const burger = document.querySelector(".nav__burger");
  const menu = document.getElementById("mobileMenu");
  if (!burger || !menu) return;
  const toggle = (open) => {
    const isOpen = open ?? !menu.classList.contains("is-open");
    menu.classList.toggle("is-open", isOpen);
    menu.hidden = !isOpen;
    burger.setAttribute("aria-expanded", isOpen ? "true" : "false");
  };
  burger.addEventListener("click", () => toggle());
  menu.querySelectorAll("a").forEach((a) => a.addEventListener("click", () => toggle(false)));
}

/* ---------- scroll reveal + staggering + count-up + caravan line ---------- */
function initReveal() {
  // pre-index grouped items for CSS stagger
  document.querySelectorAll(".caravan .stop, .steplist .step, .stats .stat, .accordion .ac")
    .forEach((el, i, list) => {
      // index within its own parent
      const siblings = [...el.parentElement.children].filter((c) => c.classList.contains(el.classList[0]) || c.classList.contains("stop") || c.classList.contains("step") || c.classList.contains("stat") || c.classList.contains("ac"));
      el.style.setProperty("--i", siblings.indexOf(el));
    });

  // assign varied entrance flavours so no two neighbours animate alike
  const stat = ["reveal--left", "reveal--scale", "reveal--right"];
  document.querySelectorAll(".stats .stat").forEach((el, i) => el.classList.add("reveal", stat[i % 3]));
  document.querySelectorAll(".steplist .step").forEach((el, i) => el.classList.add(i % 2 ? "reveal--right" : "reveal--left"));
  document.querySelectorAll(".accordion .ac").forEach((el) => el.classList.add("reveal--left"));
  document.querySelectorAll(".caravan .stop").forEach((el) => el.classList.add("reveal--scale"));
  document.querySelector(".who__text .h-display")?.classList.add("reveal--blur");
  document.querySelector(".apply__kicker")?.classList.add("reveal--blur");
  document.querySelector(".apply .card")?.classList.add("reveal--scale");

  if (reduceMotion) {
    document.querySelectorAll(".reveal").forEach((el) => el.classList.add("is-in"));
    document.querySelector(".caravan")?.classList.add("is-in");
    runCountUps(true);
    return;
  }

  // bidirectional: toggle is-in as elements enter/leave, so they replay on scroll up and down
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        const el = entry.target;
        if (entry.isIntersecting) {
          // direction-aware only for plain reveals (variants keep their own axis)
          if (!/reveal--/.test(el.className)) {
            const top = entry.rootBounds ? entry.rootBounds.top : 0;
            el.classList.toggle("from-above", entry.boundingClientRect.top < top);
          }
          el.classList.add("is-in");
          if (el.classList.contains("stat")) runCountUps(false);
        } else {
          el.classList.remove("is-in");
        }
      });
    },
    { threshold: 0.16, rootMargin: "0px 0px -6% 0px" }
  );

  document.querySelectorAll(".reveal").forEach((el) => io.observe(el));
  // caravan line draws in/out both directions (it is not a .reveal wrapper)
  const caravan = document.querySelector(".caravan");
  if (caravan) io.observe(caravan);
}

let countsDone = false;
function runCountUps(instant) {
  if (countsDone) return;
  countsDone = true;
  document.querySelectorAll("[data-count]").forEach((el) => {
    const target = parseInt(el.dataset.count, 10);
    if (instant || reduceMotion) { el.textContent = String(target); return; }
    const dur = 900, start = performance.now();
    const tick = (now) => {
      const p = Math.min(1, (now - start) / dur);
      const eased = 1 - Math.pow(1 - p, 3);
      el.textContent = String(Math.round(eased * target));
      if (p < 1) requestAnimationFrame(tick);
    };
    requestAnimationFrame(tick);
  });
}

/* ---------- scroll colour journey: tag body with the active section ---------- */
function initSectionFx() {
  const map = [[".hero","hero"],["#who","who"],["#how","how"],["#cities","cities"],["#faq","faq"],["#apply","apply"]];
  const secs = map.map(([sel,k]) => [document.querySelector(sel), k]).filter(([el]) => el);
  const set = (k) => {
    document.body.className = document.body.className.replace(/\bsec-\w+/g, "").trim();
    document.body.classList.add("sec-" + k);
  };
  set("hero");
  const io = new IntersectionObserver(
    (ents) => ents.forEach((e) => {
      if (!e.isIntersecting) return;
      const hit = secs.find(([el]) => el === e.target);
      if (hit) set(hit[1]);
    }),
    { rootMargin: "-45% 0px -45% 0px", threshold: 0 }
  );
  secs.forEach(([el]) => io.observe(el));
}

