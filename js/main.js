/* ---------- magnetic CTA (fine pointer, motion-on only) ---------- */

function initNavIndicator() {
  const nav = document.querySelector('.nav__desktop');
  const indicator = document.querySelector('.nav__indicator');
  const links = nav?.querySelectorAll('a');
  
  if (!nav || !indicator || !links.length) return;
  
  // Set initial position based on link widths
  let currentOffset = 40; // starting padding-left
  
  links.forEach((link, index) => {
    if (index > 0) {
      currentOffset += 32; // gap between links
    }
    // Store offset for each link
    link.dataset.offset = currentOffset;
    currentOffset += link.offsetWidth;
  });
  
  // Update offsets on resize
  window.addEventListener('resize', debounce(() => {
    let offset = 40;
    links.forEach((link, index) => {
      if (index > 0) offset += 32;
      link.dataset.offset = offset;
      offset += link.offsetWidth;
    });
  }, 150));
  
  // Move indicator on hover
  links.forEach(link => {
    link.addEventListener('mouseenter', () => {
      const offset = link.dataset.offset;
      indicator.style.setProperty('--link-offset', offset);
      indicator.style.height = '24px';
      indicator.style.opacity = '1';
    });
    
    link.addEventListener('mouseleave', () => {
      indicator.style.height = '0';
      indicator.style.opacity = '0';
    });
  });
}

function initMagnetic() {
  if (
    reduceMotion ||
    !window.matchMedia(
      "(hover: hover) and (pointer: fine)"
    ).matches
  ) {
    return;
  }

  document
    .querySelectorAll(
      ".hero__cta .btn, .apply .btn--pop"
    )
    .forEach((btn) => {
      let raf = null;

      btn.addEventListener("pointermove", (e) => {
        const r = btn.getBoundingClientRect();

        const dx =
          (e.clientX -
            (r.left + r.width / 2)) *
          0.22;

        const dy =
          (e.clientY -
            (r.top + r.height / 2)) *
          0.35;

        if (raf) {
          cancelAnimationFrame(raf);
        }

        raf = requestAnimationFrame(() => {
          btn.style.translate =
            `${dx}px ${dy}px`;
        });
      });

      btn.addEventListener("pointerleave", () => {
        if (raf) {
          cancelAnimationFrame(raf);
        }

        btn.style.translate = "";
      });
    });
}

/* ============================================================
   Casting form: validation, states, and the submit hook
   ============================================================ */

function initForm() {
  const form =
    document.getElementById("castingForm");

  if (!form) return;

  const phone =
    document.getElementById("f-phone");

  const submitBtn =
    document.getElementById("submitBtn");

  // Gentle +998 prefill.
  phone?.addEventListener("focus", () => {
    if (!phone.value.trim()) {
      phone.value = "+998 ";
    }
  });

  // Clear a field's error as the user fixes it.
  form
    .querySelectorAll("input, select")
    .forEach((el) => {
      el.addEventListener(
        "input",
        () => setFieldError(el, false)
      );

      el.addEventListener(
        "change",
        () => setFieldError(el, false)
      );
    });

  form.addEventListener(
    "submit",
    async (e) => {
      e.preventDefault();

      const lang = getLang();
      const errors = validate(
        form,
        lang
      );

      if (errors.length) {
        errors.forEach(({ el }) =>
          setFieldError(el, true)
        );

        errors[0].el.focus({
          preventScroll: false,
        });

        return;
      }

      const data = {
        name: form.name.value.trim(),

        age: Number(
          form.age.value
        ),

        city: form.city.value,

        cityLabel:
          form.city.options[
            form.city.selectedIndex
          ].textContent,

        phone:
          form.phone.value.trim(),

        consent:
          form.consent.checked,

        lang,

        submittedAt:
          new Date().toISOString(),
      };

      submitBtn.classList.add(
        "is-loading"
      );

      submitBtn
        .querySelector(".btn__label")
        .textContent =
        DICT[lang].submit_loading;

      try {
        await submitCasting(data);

        showSuccess();
      } catch (err) {
        console.error(
          "[UPOP] submit failed:",
          err
        );

        submitBtn.classList.remove(
          "is-loading"
        );

        submitBtn
          .querySelector(".btn__label")
          .textContent =
          DICT[lang].submit;

        alert(
          DICT[lang].err_phone &&
            "Xatolik. Qayta urinib ko'ring / Ошибка. Попробуйте ещё раз / Something went wrong, please try again."
        );
      }
    }
  );
}

function validate(form, lang) {
  const errs = [];

  const name = form.name;
  const age = form.age;
  const city = form.city;
  const phone = form.phone;
  const consent = form.consent;

  if (
    name.value.trim().length < 2
  ) {
    errs.push({ el: name });
  }

  const ageNum =
    Number(age.value);

  if (
    !age.value ||
    !Number.isInteger(ageNum) ||
    ageNum < 15 ||
    ageNum > 21
  ) {
    errs.push({ el: age });
  }

  if (!city.value) {
    errs.push({ el: city });
  }

  const digits =
    phone.value.replace(/\D/g, "");

  if (digits.length < 9) {
    errs.push({ el: phone });
  }

  if (!consent.checked) {
    errs.push({ el: consent });
  }

  return errs;
}

function setFieldError(el, on) {
  // Consent checkbox has its own error node
  // outside .field.
  if (el.id === "f-consent") {
    const node =
      document.querySelector(
        '[data-err="consent"]'
      );

    if (node) {
      node.hidden = !on;
    }

    return;
  }

  const field =
    el.closest(".field");

  if (!field) return;

  field.classList.toggle(
    "has-err",
    on
  );

  const errNode =
    field.querySelector(
      ".field__err"
    );

  if (errNode) {
    errNode.hidden = !on;
  }
}

function showSuccess() {
  const wrap =
    document.getElementById(
      "formwrap"
    );

  const ok =
    document.getElementById(
      "success"
    );

  if (wrap) {
    wrap.hidden = true;
  }

  if (ok) {
    ok.hidden = false;

    ok.scrollIntoView({
      behavior:
        reduceMotion
          ? "auto"
          : "smooth",
      block: "center",
    });
  }
}

